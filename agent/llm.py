"""
agent/llm.py - Local LLM Client for Ollama.

This module is responsible for:
1. Sending prompts to the local Ollama instance over HTTP.
2. Receiving the text generated by the model.
3. Catching and clearly explaining connection, timeout, and model errors.
"""

from typing import Optional
import requests
import config


class LLMError(Exception):
    """Custom exception raised when communication with Ollama fails."""
    pass


class OllamaClient:
    """
    Client for interacting with local Ollama models.
    """

    def __init__(
        self,
        base_url: str = config.OLLAMA_BASE_URL,
        model: str = config.OLLAMA_MODEL,
        timeout: int = config.REQUEST_TIMEOUT
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.timeout = timeout
        self.generate_endpoint = f"{self.base_url}/api/generate"

    def generate(self, prompt: str, system: Optional[str] = None) -> str:
        """
        Sends a prompt to the Ollama model and returns the text response.

        Args:
            prompt: The user instruction or text to send to the model.
            system: Optional system prompt to define the persona/behavior.

        Returns:
            The generated response string from Ollama.

        Raises:
            LLMError: If Ollama is offline, the model is missing, or the request fails.
        """
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False  # Return the complete response at once rather than chunked
        }

        if system:
            payload["system"] = system

        try:
            response = requests.post(
                self.generate_endpoint,
                json=payload,
                timeout=self.timeout
            )
        except requests.exceptions.ConnectionError as err:
            raise LLMError(
                f"[Ollama Error] Could not connect to Ollama at '{self.base_url}'. "
                f"Please ensure Ollama is running on your machine (e.g. run 'ollama serve')."
            ) from err
        except requests.exceptions.Timeout as err:
            raise LLMError(
                f"[Ollama Error] Request timed out after {self.timeout} seconds. "
                f"The model may be overloaded or still loading."
            ) from err
        except requests.exceptions.RequestException as err:
            raise LLMError(
                f"[Ollama Error] An unexpected network error occurred: {err}"
            ) from err

        # Check HTTP status code (e.g., 404 if the model name is incorrect)
        if response.status_code == 404:
            raise LLMError(
                f"[Ollama Error] Model '{self.model}' not found (HTTP 404). "
                f"Make sure you have pulled it by running: 'ollama pull {self.model}'."
            )
        elif response.status_code != 200:
            raise LLMError(
                f"[Ollama Error] Received HTTP {response.status_code}: {response.text}"
            )

        # Parse JSON response
        try:
            data = response.json()
        except ValueError as err:
            raise LLMError(
                f"[Ollama Error] Failed to decode JSON response from Ollama: {response.text}"
            ) from err

        if "response" not in data:
            raise LLMError(
                f"[Ollama Error] Unexpected response format from Ollama. Missing 'response' key: {data}"
            )

        return data["response"].strip()
